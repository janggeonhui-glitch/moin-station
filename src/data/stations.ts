function buildStations(): Map<string, Station> {
  const map = new Map<string, Station>();
  for (const row of TABLE.split('\n')) {
    const [name, lat, lng, lines] = row.split('|');
    if (!name || !lat || !lng || !lines) continue;
    map.set(name, { name, lat: Number(lat), lng: Number(lng), lines: lines.split(',') });
  }
  for (const a of AREAS) {
    if (!map.has(a.station)) map.set(a.station, { name: a.station, lat: a.lat, lng: a.lng, lines: a.lines });
  }
  return map;
}

export const STATIONS: ReadonlyMap<string, Station> = buildStations();

export const STATION_LIST: readonly Station[] = [...STATIONS.values()].sort((a, b) =>
  a.name.localeCompare(b.name, 'ko'),
);
